BEGIN;

ALTER TABLE reservations ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
    pg_get_serial_sequence('reservations', 'id'),
    GREATEST(COALESCE(MAX(id), 1), 1),
    COALESCE(MAX(id) > 0, false)
)
FROM reservations;

CREATE INDEX reservations_room_day_start_idx
    ON reservations (hashtext(room), (date_ticks / 864000000000), start_time_ticks);

COMMIT;
