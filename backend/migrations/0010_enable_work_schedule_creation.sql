BEGIN;

ALTER TABLE work_schedule_entries ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Links can outlive their schedules. Keep newly generated IDs clear of imported references.
WITH highest_id AS (
    SELECT GREATEST(
        (SELECT MAX(id) FROM work_schedule_entries),
        (SELECT MAX(target_work_schedule_entry_id) FROM notifications),
        (SELECT MAX(work_schedule_entry_id) FROM chatwork_delivery_logs),
        0
    ) AS id
)
SELECT setval(pg_get_serial_sequence('work_schedule_entries', 'id'), GREATEST(id, 1), id > 0)
FROM highest_id;

COMMIT;
