CREATE TABLE chatwork_delivery_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id integer NOT NULL,
    work_schedule_entry_id integer,
    delivery_type text NOT NULL,
    delivery_key text UNIQUE,
    target_user_id integer,
    scheduled_start_time_ticks bigint NOT NULL CHECK (scheduled_start_time_ticks BETWEEN 0 AND 3155378975999999999),
    room_id text,
    status text NOT NULL,
    error_message text,
    attempted_at_ticks bigint NOT NULL CHECK (attempted_at_ticks BETWEEN 0 AND 3155378975999999999),
    sent_at_ticks bigint CHECK (sent_at_ticks BETWEEN 0 AND 3155378975999999999),
    message text NOT NULL,
    created_at_ticks bigint NOT NULL CHECK (created_at_ticks BETWEEN 0 AND 3155378975999999999)
);
