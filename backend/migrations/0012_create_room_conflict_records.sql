BEGIN;

CREATE TABLE room_conflict_records (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type integer NOT NULL,
    status integer NOT NULL,
    occurred_at_ticks bigint NOT NULL CHECK (occurred_at_ticks BETWEEN 0 AND 3155378975999999999),
    room_name text NOT NULL,
    -- Historical references survive deletion from the source tables.
    reservation_id_a integer,
    reservation_id_b integer,
    impact integer NOT NULL,
    cause integer NOT NULL,
    description text NOT NULL,
    resolution text NOT NULL,
    detection_key text UNIQUE,
    reported_by_user_id integer,
    created_at_ticks bigint NOT NULL CHECK (created_at_ticks BETWEEN 0 AND 3155378975999999999),
    updated_at_ticks bigint CHECK (updated_at_ticks BETWEEN 0 AND 3155378975999999999)
);

CREATE INDEX room_conflict_records_occurred_id_idx
    ON room_conflict_records (occurred_at_ticks DESC, id DESC);

COMMIT;
